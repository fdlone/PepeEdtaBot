def random_sentence() -> list[str]:
    length = random.randint(5, 15)
    return random.choices(VOCAB, k=length)


async def run(db_path: str, chat_id: int, num_messages: int) -> None:
    database = Database(db_path)
    await database.init()

    print(f"Wiping chat {chat_id} ...")
    await database.clear_chat(chat_id)
    print("  cleared")

    token_total = 0
    for i in range(num_messages):
        tokens = random_sentence()
        raw_text = " ".join(tokens)
        volume = await database.save_message_and_update_model(chat_id, raw_text, tokens)
        token_total += len(tokens)
        if (i + 1) % 200 == 0:
            print(f"  {i + 1}/{num_messages} messages — model volume: {volume}")

    print(f"\nDone. Vocab size: {len(VOCAB)}, inserted {num_messages} messages "
          f"(~{token_total} tokens) into chat {chat_id}.")
    await database.close()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--chat-id", type=int, required=True)
    parser.add_argument("--messages", type=int, default=2000)
    parser.add_argument("--db", type=str, default="data/markov.db")
    args = parser.parse_args()
    asyncio.run(run(args.db, args.chat_id, args.messages))


if __name__ == "__main__":
    main()
