"""Общий словарь отказов ответа (M3R-021, роадмап §3).

До него одно и то же явление называлось по-разному в трёх местах: строкой
трассы (`short_context_copy`), фразой конвейера («копия обучающего 1:1») и
формулировкой человека в раунде оценки. Классы отсюда — единственный источник
имён для всех трёх: телеметрии отклонений, рубрики соло-раунда (M3R-020) и
заявок на фичи, которые обязаны называть свои целевые классы.

Покрытие автоматикой **частичное, и это заявленное свойство, а не пробел в
реализации**: сегодня причины отклонения дают четыре класса из девяти.
Остальные приходят от ручной рубрики (нерелевантность, генеричность, промах
мема), от структурных метрик (схлопывание маршрутов) или от разбора (ошибка
скорера). Поэтому пустой класс в разбивке читается как «нет автоматического
источника», а не как «таких отказов не было» — различие держит
``AUTOMATIC_CLASSES``.
"""

from __future__ import annotations

from enum import StrEnum


class FailureClass(StrEnum):
    """Девять классов отказа ответа (роадмап §3).

    Закрытое перечисление: класс — ось, по которой сравниваются фичи, раунды и
    телеметрия, поэтому опечатка обязана быть ошибкой, а не новой категорией.
    """

    IRRELEVANT = "F1_irrelevant"
    CONTEXT_COPY = "F2_context_copy"
    GENERIC = "F3_generic"
    STALE = "F4_stale"
    MEME_MISS = "F5_meme_miss"
    STRUCTURAL_REPEAT = "F6_structural_repeat"
    MALFORMED = "F7_malformed"
    ROUTE_COLLAPSE = "F8_route_collapse"
    SCORER_ERROR = "F9_scorer_error"


# Причины отклонения кандидата → классы. Обоснование каждой строки — в design
# заявки `failure-taxonomy` (D1); здесь только следствия.
#
# Причины «не из чего генерировать» (`no_starts`, `no_start_transition`)
# намеренно отсутствуют: это отказ ДО появления текста, свойство данных чата, а
# не ответа. Записать их в «малформированность» значило бы смешать «бот не смог
# сказать» с «бот сказал плохо» — ровно то различение, ради которого таксономия
# и заводится (design D4).
#
# Причины заданы литералами, а не импортом констант: словарь отказов — лист
# графа импортов, он не должен зависеть ни от генератора, ни от конвейера
# ответа (оба импортируют телеметрию, которая импортирует этот модуль, — вышел
# бы цикл). Совпадение литералов с константами кода закреплено тестом
# `tests/test_failure_taxonomy.py`, поэтому расхождение — падение сборки, а не
# тихо потерянная разметка.
REASON_TO_CLASS: dict[str, FailureClass] = {
    "short_context_copy": FailureClass.CONTEXT_COPY,
    "context_heavy": FailureClass.CONTEXT_COPY,
    "low_diversity": FailureClass.STRUCTURAL_REPEAT,
    "result_too_short": FailureClass.MALFORMED,
    "Generated reply repeats recent chat content": FailureClass.STALE,
    "Generated text is a training sample 1:1": FailureClass.STALE,
}

# Классы, у которых сегодня есть автоматический источник. Всё остальное
# существует в словаре ради рубрики и разбора — и обязано читаться как
# «источника нет», а не как «отказов нет».
AUTOMATIC_CLASSES: frozenset[FailureClass] = frozenset(REASON_TO_CLASS.values())

# Разряд для причины, которой ещё не назначили класс: новая причина обязана
# быть видна как невыполненная работа, а не уменьшать сумму по классам
# (прецедент знаменателей M3R-141).
UNMAPPED = "unmapped"


def classify_reason(reason: str) -> FailureClass | None:
    """Класс причины отклонения или ``None``, если она не размечена."""
    return REASON_TO_CLASS.get(reason)
