# Template invariants (enforced by tests/test_pivo_message_builder.py).
#
# {mentions_inline}
#   Either an empty string or a mention list carrying its own leading space
#   (" @a @b"). Every top template already opens with its own collective
#   vocative, so the mention list is glued to it as an optional appendix:
#   "Так, конченые{mentions_inline}, собираемся ..." reads correctly both with
#   and without mentions. Never write " {mentions_inline}" and never place a
#   noun phrase in this slot: the slot is governed by the surrounding sentence
#   (apposition, accusative, dative), so a noun phrase produced case errors and
#   doubled vocatives ("Так, конченые конченый состав чата").
#
# {target_phrase}
#   Raw user text of unknown grammatical form: it may be a noun ("фильмы") or an
#   infinitive ("посмотреть фильм"). It may therefore stand only in a free
#   position — at the start of a line, or right after "— ", ": " or "у нас " —
#   never after a preposition or a verb that governs a case ("заняться X",
#   "взяться за X").
#
# {time_phrase_soft}
#   May expand to a clause with a comma inside ("ближе к вечеру, как только
#   ..."), so it is only ever sentence-final, right before the closing dot.
#
# Sub-pool slots (PIVO_SUB_POOLS)
#   A template may also carry a slot named after a key of PIVO_SUB_POOLS
#   ("{dispute_topic}"); the builder expands it to a random pool entry BEFORE
#   the final context substitution, and an entry may itself contain sub-pool
#   slots (depth-capped). Sub-pool entries are author-controlled literals in a
#   fixed grammatical shape per pool — mind the case the surrounding sentence
#   governs, same as with the slots above.

